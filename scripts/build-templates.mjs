// Regenerates templates.js from the example workflows in tests/fixtures/.
// Run `node scripts/build-templates.mjs` after refreshing a fixture. The output is committed,
// so the site itself needs no build step. `node --test tests/` fails if templates.js is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = {
  CODE_REVIEW_TEMPLATE: 'code-review.yml',
  AI_SCAN_TEMPLATE: 'ai-scan.yml',
  SECURITY_SCAN_TEMPLATE: 'security-scan.yml',
};

let out = '// Generated by scripts/build-templates.mjs from tests/fixtures/*.yml. Do not edit by hand.\n';
for (const [name, file] of Object.entries(sources)) {
  const text = readFileSync(join(root, 'tests', 'fixtures', file), 'utf8');
  out += `export const ${name} = ${JSON.stringify(text)};\n`;
}
writeFileSync(join(root, 'templates.js'), out);
console.log('wrote templates.js');
